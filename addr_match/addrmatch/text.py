"""Нормализация строк: фонетический ключ и словари.

Фонетический ключ сворачивает ровно те замены, которые видны в voice-шуме:
редукция гласных (о/а, е/и/ы), оглушение (г/к, д/т, з/с, в/ф, б/п),
«тс» -> «ц», окончание «-ого» -> «-ова». После свёртки «пирфомайский»
и «первомайский» дают одинаковый ключ, и дальше хватает обычного Левенштейна.
"""
import os
import re

# Флаги для абляций (scripts/ablation.py). В бою не используются.
_NO_PHONETIC = bool(os.environ.get("ADDR_NO_PHONETIC"))
_NO_STEM = bool(os.environ.get("ADDR_NO_STEM"))

_MAP = str.maketrans({
    "о": "а", "я": "а", "ы": "и", "е": "и", "э": "и", "й": "и", "ю": "у",
    "б": "п", "в": "ф", "г": "к", "д": "т", "ж": "ш", "з": "с", "щ": "ш",
})
_OGO = re.compile(r"(?<=[а-я])(ого|его)\b")
_DOUBLE = re.compile(r"(.)\1+")
_TRAIL_VOWELS = re.compile(r"[аиу]+$")


def key(s: str) -> str:
    """Фонетический ключ одного слова или фразы (пробелы сохраняются)."""
    s = s.lower().replace("ё", "е")
    if _NO_PHONETIC:
        return s
    s = s.replace("ъ", "").replace("ь", "")
    s = _OGO.sub("ова", s)
    s = s.replace("тс", "ц").replace("дс", "ц")
    s = s.translate(_MAP)
    return _DOUBLE.sub(r"\1", s)


_ORD_SUFFIX = ("я", "й", "го", "ая", "ой", "ий", "ый", "е", "ое")


def merge_ordinals(tokens):
    """«2-я» токенайзер режет на «2» и «я». Склеиваем обратно в «2я».

    Нужно в двух местах одинаково: в запросе, чтобы «2я» не ушло в номер дома,
    и в эталоне, чтобы «6-й» не превратился в «6» (одиночная «й» выбрасывается
    как инициал) и совпал с запросом.
    """
    out = []
    for t in tokens:
        if out and out[-1].isdigit() and t in _ORD_SUFFIX:
            out[-1] = out[-1] + t
        else:
            out.append(t)
    return out


def stem(word_key: str) -> str:
    """Срезает хвостовые гласные ключа: «санаторной»/«санаторная» -> «санатарн»."""
    if _NO_STEM:
        return word_key
    st = _TRAIL_VOWELS.sub("", word_key)
    return st if len(st) >= 3 else word_key


def stem_key(tokens) -> str:
    """Ключ для сравнения улиц: стемы слов без пробелов (устойчиво к слипанию)."""
    return "".join(stem(key(t)) for t in tokens)


def full_key(tokens) -> str:
    return "".join(key(t) for t in tokens)


