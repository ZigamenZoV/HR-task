_PUNCT = re.compile(r"[,.;:!?()\"'«»\\]")
_LETTER_DIGIT = re.compile(r"(?<=[а-яё])(?=\d)")
_SLASH = re.compile(r"\s*/\s*")


def tokenize(raw: str):
    s = raw.lower().replace("ё", "е")
    s = _SLASH.sub(" / ", s)
    s = _PUNCT.sub(" ", s)
    s = _LETTER_DIGIT.sub(" ", s)          # «ленина54» -> «ленина 54», «д67» -> «д 67»
    toks = []
    for t in s.split():
        # дефис внутри слов меняем на пробел: «30-летия» -> «30 летия», «2-я» -> «2 я»
        if "-" in t and not re.fullmatch(r"[а-я]{1,3}-[а-я]{1,3}", t):  # «пр-т», «б-р» оставляем
            toks.extend(p for p in t.split("-") if p)
        else:
            toks.append(t.replace("-", ""))
    return toks
